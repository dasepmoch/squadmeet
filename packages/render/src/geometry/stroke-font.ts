export type Polyline = [number, number][];

/** Returns polylines for `text`, laid out left-to-right in glyph units (advance 5.6 per char). */
export function layoutStrokeText(text: string): { lines: Polyline[]; width: number } {
  const lines: Polyline[] = [];
  let x = 0;
  for (const ch of text.toUpperCase()) {
    if (ch === ' ') {
      x += 4;
      continue;
    }
    const glyph = GLYPHS[ch];
    if (glyph) {
      for (const stroke of glyph.split('|')) {
        const pts = stroke
          .trim()
          .split(/\s+/)
          .map((pair): [number, number] => {
            const [a, b] = pair.split(',').map(Number);
            return [(a ?? 0) + x, b ?? 0];
          });
        if (pts.length >= 2) lines.push(pts);
      }
    }
    x += 5.6;
  }
  return { lines, width: Math.max(0, x - 1.6) };
}
